using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Net;
using System.Reflection;
using System.Text;
using System.Threading;
using System.Threading.Tasks;
using System.Windows.Forms;
using UnderTree.WordAddin;

internal sealed class NativeMcpClient
{
    private static readonly Dictionary<string, NativeMcpClient> defaults = new Dictionary<string, NativeMcpClient>();
    private readonly string address;
    internal readonly string Session;
    internal readonly string Conversation;
    internal static Action<string> Trace;
    internal string Scope { get {
        if (Conversation != null) throw new InvalidOperationException("Labelled native scopes are generated by the server; inspect their actual owner in the native fixture.");
        return "mcp_" + McpCoordination.Digest(Session) + ":default";
    } }
    internal string NativeRequestId(string requestId) { return PolicyEngine.Hash(Scope + "\0" + requestId); }

    internal NativeMcpClient(string address, string name, string conversation = null)
    {
        this.address = address; Conversation = conversation;
        var request = Request("POST", null);
        using (var response = Send(request, new { jsonrpc = "2.0", id = 1, method = "initialize", @params = new {
            protocolVersion = "2025-06-18", clientInfo = new { name = name, version = "native-test" }, capabilities = new { } } }))
        {
            Session = response.Headers["Mcp-Session-Id"];
            if (String.IsNullOrEmpty(Session)) throw new Exception("Initialization omitted its MCP session ID.");
            using (var reader = new StreamReader(response.GetResponseStream()))
                if (!reader.ReadToEnd().Contains(McpCoordination.Protocol)) throw new Exception("Initialization omitted its coordination contract.");
        }
    }

    internal static NativeMcpClient ForAddress(string address)
    {
        NativeMcpClient client;
        if (!defaults.TryGetValue(address, out client)) { client = new NativeMcpClient(address, "native-default"); defaults.Add(address, client); }
        return client;
    }

    internal static void ApplyLegacyTracked(WordEditor editor, object document, object request, NativeMcpClient client = null)
    {
        // Historical review fixtures retain their old pending receipt, then use the real native tracked transaction.
        // New MCP prompt submissions must continue through Call/Review and are never converted here implicitly.
        var args = Map(request);
        var states = (Dictionary<long, WordDocumentReview>)typeof(WordEditor).GetField("documents", BindingFlags.Instance | BindingFlags.NonPublic).GetValue(editor);
        WordDocumentReview state = states[WordSnapshot.Identity(document)];
        PolicyState prior = state.Policy.ExportState();
        bool shared = state.Policy.IsShared;
        WordSnapshot snapshot = WordSnapshot.Capture(document);
        string native = state.NativeEdit.NativeIdentity(document, snapshot);
        string scope = client == null ? "default" : client.Scope;
        string requestId = (string)args["request_id"];
        string id = client == null ? requestId : client.NativeRequestId(requestId);
        var proposal = new Proposal { Id = id, DocumentId = (string)args["manuscript_id"], Revision = (string)args["revision"],
            From = Convert.ToInt32(args["from"]), To = Convert.ToInt32(args["to"]), Quote = (string)args["quote"],
            Replacement = (string)args["replacement"], Rationale = args.ContainsKey("rationale") ? (string)args["rationale"] : "" };
        if (args.ContainsKey("replacementParts"))
            proposal.ReplacementParts = McpEndpoint.Json().Deserialize<List<ReplacementPart>>(McpEndpoint.Json().Serialize(args["replacementParts"]));
        UnderTree.WordAddin.Authorization authorization = state.Policy.Submit(proposal, (string)args["context_id"], snapshot.MainText, snapshot.Revision, scope);
        if (authorization.AlreadyRecorded) throw new InvalidOperationException("A legacy setup needs a new request identity; replay through the actual MCP path.");
        Proposal legacyReceipt = state.Policy.Proposals.Single(receipt => receipt.Id == id);
        legacyReceipt.Status = "pending";
        state.Snapshot = snapshot;
        try
        {
            typeof(WordEditor).GetMethod("Apply", BindingFlags.Instance | BindingFlags.NonPublic)
                .Invoke(editor, new object[] { state, id, false, true });
        }
        catch (TargetInvocationException error)
        {
            // A refused preflight never started a native transaction. Restore only its uncommitted fixture receipt.
            if (legacyReceipt.Status == "pending" && state.NativeEdit.NativeIdentity(document) == native)
            {
                state.Policy = (PolicyEngine)typeof(WordEditor).GetMethod("CreatePolicy", BindingFlags.Static | BindingFlags.NonPublic)
                    .Invoke(null, new object[] { prior });
                if (shared) state.Policy.Share(state.Id);
                state.Snapshot = null;
            }
            throw error.InnerException;
        }
        if (state.Policy.Proposals.Single(recorded => recorded.Id == id).Status != "tracked")
            throw new InvalidOperationException("The historical fixture did not complete its real native tracked application.");
    }

    internal Dictionary<string, object> Call(string name, object arguments, bool omitConversation = false)
    { return Wait(CallAsync(name, arguments, omitConversation)); }

    internal Task<Dictionary<string, object>> CallAsync(string name, object arguments, bool omitConversation = false)
    {
        return Task.Run(delegate
        {
            if (Trace != null) Trace("http-start " + name);
            try
            {
            object parameters = Conversation == null || omitConversation ? (object)new { name = name, arguments = arguments } :
                new { name = name, arguments = arguments, _meta = new Dictionary<string, object> { { "openai/session", Conversation } } };
            using (var response = Send(Request("POST", Session), new { jsonrpc = "2.0", id = Guid.NewGuid().ToString("N"), method = "tools/call", @params = parameters }))
            using (var reader = new StreamReader(response.GetResponseStream()))
            {
                var envelope = McpEndpoint.Json().Deserialize<Dictionary<string, object>>(reader.ReadToEnd());
                if (envelope.ContainsKey("error")) throw new Exception(McpEndpoint.Json().Serialize(envelope["error"]));
                return Map(envelope["result"]);
            }
            }
            finally { if (Trace != null) Trace("http-end " + name); }
        });
    }

    internal int Delete()
    {
        return Wait(Task.Run(delegate
        {
            using (var response = (HttpWebResponse)Request("DELETE", Session).GetResponse()) return (int)response.StatusCode;
        }));
    }

    private HttpWebRequest Request(string method, string session)
    {
        var request = (HttpWebRequest)WebRequest.Create(address);
        request.Proxy = null; request.Method = method; request.KeepAlive = false;
        request.ServicePoint.Expect100Continue = false;
        request.Timeout = 20000; request.ReadWriteTimeout = 20000;
        request.Accept = "application/json, text/event-stream";
        request.Headers["MCP-Protocol-Version"] = "2025-06-18";
        if (session != null) request.Headers["Mcp-Session-Id"] = session;
        return request;
    }

    private static HttpWebResponse Send(HttpWebRequest request, object payload)
    {
        request.ContentType = "application/json";
        byte[] bytes = Encoding.UTF8.GetBytes(McpEndpoint.Json().Serialize(payload));
        request.ContentLength = bytes.Length;
        using (Stream stream = request.GetRequestStream()) stream.Write(bytes, 0, bytes.Length);
        return (HttpWebResponse)request.GetResponse();
    }

    internal static T Wait<T>(Task<T> pending)
    {
        Stopwatch timeout = Stopwatch.StartNew();
        while (!pending.IsCompleted && timeout.ElapsedMilliseconds < 25000) { Application.DoEvents(); Thread.Sleep(10); }
        if (!pending.IsCompleted) throw new TimeoutException("The isolated native MCP operation did not finish.");
        return pending.GetAwaiter().GetResult();
    }

    internal static Dictionary<string, object> Map(object value)
    { return McpEndpoint.Json().Deserialize<Dictionary<string, object>>(McpEndpoint.Json().Serialize(value)); }
}
